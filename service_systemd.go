package main

import (
	"errors"
	"flag"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

const (
	systemdUnitName     = "vekil.service"
	systemdNoLingerFlag = "no-linger"
)

type systemdServiceBackend struct {
	noLinger *bool
}

func (b *systemdServiceBackend) tool() string { return "systemctl" }

func (b *systemdServiceBackend) registerFlags(fs *flag.FlagSet) {
	b.noLinger = fs.Bool(systemdNoLingerFlag, false, "Do not enable lingering; the service then stops when you log out")
}

func (b *systemdServiceBackend) preflight(serviceDeps) error { return nil }

// defaultLogFile is empty because journald captures the service's stderr.
func (b *systemdServiceBackend) defaultLogFile(serviceDeps) (string, error) { return "", nil }

func (b *systemdServiceBackend) location(deps serviceDeps) (string, error) {
	configDir, err := deps.userConfigDir()
	if err != nil {
		return "", fmt.Errorf("resolve user config directory: %w", err)
	}
	return filepath.Join(configDir, "systemd", "user", systemdUnitName), nil
}

func (b *systemdServiceBackend) installed(deps serviceDeps) (bool, error) {
	path, err := b.location(deps)
	if err != nil {
		return false, err
	}
	_, err = os.Stat(path)
	if errors.Is(err, fs.ErrNotExist) {
		return false, nil
	}
	return err == nil, err
}

func (b *systemdServiceBackend) register(deps serviceDeps, spec serviceSpec) error {
	path, err := b.location(deps)
	if err != nil {
		return err
	}
	unit, err := renderSystemdUnit(spec.command, spec.path)
	if err != nil {
		return err
	}
	if deps.euid == 0 {
		_, _ = fmt.Fprintln(deps.stderr, "warning: installing a user service for root; run without sudo to install it for your own account")
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("create %s: %w", filepath.Dir(path), err)
	}
	if err := os.WriteFile(path, []byte(unit), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}

	// Enable lingering first: it starts the user manager when no session has.
	if b.noLinger == nil || !*b.noLinger {
		if err := deps.run(io.Discard, io.Discard, "loginctl", "enable-linger"); err != nil {
			_, _ = fmt.Fprintln(deps.stderr, "warning: could not enable lingering, so Vekil will stop when you log out; ask an administrator to run: sudo loginctl enable-linger $USER")
		}
	}
	if err := b.systemctl(deps, "daemon-reload"); err != nil {
		return err
	}
	return b.systemctl(deps, "enable", systemdUnitName)
}

func (b *systemdServiceBackend) restart(deps serviceDeps) error {
	return b.systemctl(deps, "restart", systemdUnitName)
}

func (b *systemdServiceBackend) remove(deps serviceDeps) error {
	if err := b.systemctl(deps, "disable", "--now", systemdUnitName); err != nil {
		return err
	}
	path, err := b.location(deps)
	if err != nil {
		return err
	}
	if err := os.Remove(path); err != nil && !errors.Is(err, fs.ErrNotExist) {
		return fmt.Errorf("remove %s: %w", path, err)
	}
	if err := b.systemctl(deps, "daemon-reload"); err != nil {
		_, _ = fmt.Fprintf(deps.stderr, "warning: %v\n", err)
	}
	return nil
}

func (b *systemdServiceBackend) status(deps serviceDeps) error {
	return deps.run(deps.stdout, deps.stderr, "systemctl", "--user", "status", "--no-pager", systemdUnitName)
}

func (b *systemdServiceBackend) logsHint(logFile string) string {
	if logFile != "" {
		return "tail -f " + logFile
	}
	return "journalctl --user -u vekil -f"
}

func (b *systemdServiceBackend) systemctl(deps serviceDeps, args ...string) error {
	if err := deps.run(deps.stderr, deps.stderr, "systemctl", append([]string{"--user"}, args...)...); err != nil {
		return fmt.Errorf("systemctl --user %s failed: %w\nhint: systemctl --user needs your user systemd session; log in as this user directly (not via sudo or su) and retry", strings.Join(args, " "), err)
	}
	return nil
}

func renderSystemdUnit(command []string, path string) (string, error) {
	quoted := make([]string, 0, len(command))
	for _, arg := range command {
		if err := validateServiceValue(arg); err != nil {
			return "", err
		}
		quoted = append(quoted, systemdQuoteExecArg(arg))
	}

	var b strings.Builder
	b.WriteString("# Generated by `vekil service install`. Re-run it to change server flags.\n")
	b.WriteString("[Unit]\n")
	b.WriteString("Description=Vekil proxy\n")
	b.WriteString("Documentation=https://github.com/sozercan/vekil\n\n")
	b.WriteString("[Service]\n")
	b.WriteString("Type=simple\n")
	if path != "" && validateServiceValue(path) == nil {
		b.WriteString("Environment=" + systemdQuoteEnvironment("PATH="+path) + "\n")
	}
	b.WriteString("ExecStart=" + strings.Join(quoted, " ") + "\n")
	b.WriteString("Restart=on-failure\n")
	b.WriteString("RestartSec=10\n\n")
	b.WriteString("[Install]\n")
	b.WriteString("WantedBy=default.target\n")
	return b.String(), nil
}

// systemdQuoteExecArg quotes one ExecStart argument so systemd passes it
// verbatim, without specifier or environment-variable expansion.
func systemdQuoteExecArg(arg string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`, `%`, `%%`, `$`, `$$`).Replace(arg) + `"`
}

func systemdQuoteEnvironment(assignment string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`, `%`, `%%`).Replace(assignment) + `"`
}
